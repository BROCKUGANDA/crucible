#!/usr/bin/env node
/**
 * Gate 732 — the params single source (ADR-0011).
 *
 * One JSON in, three checks out:
 *   1. INVARIANTS: the v2 bible §5.1 derived invariants, proven from the numbers
 *      before anything is generated. A violated invariant is exit 1, no output.
 *   2. CODEGEN: emits params/generated/params.rs and params/generated/params.ts,
 *      committed artifacts; `--check` regenerates in memory and diffs against
 *      the files on disk, exiting 1 on drift.
 *   3. LEGACY FREEZE: the v1 constants (LEGACY_*) are emitted verbatim and any
 *      attempt to change them is flagged in the drift diff for human eyes —
 *      the 5% law must never look like it moved.
 *
 * Run: node scripts/params-codegen.mjs          (write)
 *      node scripts/params-codegen.mjs --check  (CI drift gate)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const paramsPath = join(root, "params", "crucible.params.json");
const outDir = join(root, "params", "generated");

const P = JSON.parse(readFileSync(paramsPath, "utf8"));
const check = process.argv.includes("--check");

// ── §5.1 derived invariants ────────────────────────────────────────────────
const problems = [];
const bps = 10_000n;
const b = (x) => BigInt(x);

// 1. Seats can always be paid from the bond:
//    MAX_DOCKET × ARGUS_SEATS × SEAT_FEE_BPS ≤ (10000 − BREAK_PRIZE_BPS) × AGENT_BOND_MIN_BPS / 10000
const seatNeed = b(P.max_docket) * b(P.argus_seats) * b(P.seat_fee_bps);
const bondHave = ((bps - b(P.break_prize_bps)) * b(P.agent_bond_min_bps)) / bps;
if (seatNeed > bondHave) {
  problems.push(
    `invariant 1 violated: seats need ${seatNeed} bps of R but a minimum bond only provides ${bondHave}`,
  );
}

// 2. Breaking pays at least 5:1 at the minimum stake:
//    BREAK_PRIZE_BPS × AGENT_BOND_MIN_BPS / 10000 ≥ 5 × SKEPTIC_STAKE_MIN_BPS
const prizeAtMin = (b(P.break_prize_bps) * b(P.agent_bond_min_bps)) / bps;
const fiveXStake = 5n * b(P.skeptic_stake_min_bps);
if (prizeAtMin < fiveXStake) {
  problems.push(
    `invariant 2 violated: minimum-stake prize is ${prizeAtMin} bps of R, below 5x the ${fiveXStake} bps minimum stake`,
  );
}

// 3. Windows nest: every window bound is positive and min ≤ max.
if (P.claim_deadline_min_seconds <= 0 || P.claim_deadline_min_seconds > P.claim_deadline_max_seconds)
  problems.push("invariant 3 violated: claim deadline bounds");
if (P.skeptic_window_min_seconds <= 0 || P.skeptic_window_min_seconds > P.skeptic_window_max_seconds)
  problems.push("invariant 3 violated: skeptic window bounds");
if (P.vote_commit_window_seconds <= 0 || P.vote_reveal_window_seconds <= 0)
  problems.push("invariant 3 violated: vote windows must be positive");

// 4. Bounded life: the worst-case chain of stages stays under 50 days (4_320_000 s).
const worstLife =
  P.trial_open_max_seconds +
  P.claim_deadline_max_seconds +
  P.skeptic_window_max_seconds +
  P.break_reveal_grace_seconds +
  P.max_argus_rounds * (P.vote_commit_window_seconds + P.vote_reveal_window_seconds + 2 * 3600);
if (worstLife > 4_320_000) {
  problems.push(`invariant 4 violated: worst-case life ${worstLife}s exceeds 50 days`);
}

// 5. Seat solvency shape: the bond multiple covers the rounds a seat can be slashed in.
if (P.seat_bond_min_multiple_of_fees < 1 || P.seat_slash_bps > bps) {
  problems.push("invariant 5 violated: seat bond multiple / slash bps out of range");
}

// Legacy freeze: the v1 numbers must never drift from ADR-0002's law.
if (P.legacy_fee_bps_v1_frozen !== 500 || P.legacy_break_split_v1_frozen !== 5000) {
  problems.push(
    "legacy freeze violated: the v1 constants (500 bps fee, 50/50 split) are records, not parameters — see ADR-0011",
  );
}

if (problems.length > 0) {
  console.error(`params invariants FAILED:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

// ── codegen ────────────────────────────────────────────────────────────────
const rust = `// GENERATED by scripts/params-codegen.mjs from params/crucible.params.json — gate 732.
// Do not edit: change the JSON, re-run the generator, commit the diff.
// v2 arena parameters (ADR-0011). The v1 constants at the bottom are frozen records.

#![allow(dead_code)]

// ARENA_FEE_BPS, not FEE_BPS: CrucibleTrials.sol:143 owns a live FEE_BPS = 500, and a
// generated FEE_BPS = 1500 one import away from it is the exact confusion AGENTS.md names
// as the product pivot. The arena's fee is therefore only addressable by its arena name.
pub const ARENA_FEE_BPS: u64 = ${P.fee_bps};
pub const TRIAL_OPEN_MAX_SECONDS: u64 = ${P.trial_open_max_seconds};
pub const AGENT_BOND_MIN_BPS: u64 = ${P.agent_bond_min_bps};
pub const CLAIM_DEADLINE_MIN_SECONDS: u64 = ${P.claim_deadline_min_seconds};
pub const CLAIM_DEADLINE_MAX_SECONDS: u64 = ${P.claim_deadline_max_seconds};
pub const MAX_ACTIVE_CLAIMS: u64 = ${P.max_active_claims};
pub const SKEPTIC_WINDOW_MIN_SECONDS: u64 = ${P.skeptic_window_min_seconds};
pub const SKEPTIC_WINDOW_MAX_SECONDS: u64 = ${P.skeptic_window_max_seconds};
pub const SKEPTIC_STAKE_MIN_BPS: u64 = ${P.skeptic_stake_min_bps};
pub const BREAK_REVEAL_GRACE_SECONDS: u64 = ${P.break_reveal_grace_seconds};
pub const MAX_DOCKET: usize = ${P.max_docket};
pub const BREAK_PRIZE_BPS: u64 = ${P.break_prize_bps};
pub const ARGUS_SEATS: usize = ${P.argus_seats};
pub const ARGUS_QUORUM: usize = ${P.argus_quorum};
pub const SEAT_FEE_BPS: u64 = ${P.seat_fee_bps};
pub const SEAT_BOND_MIN_MULTIPLE: u64 = ${P.seat_bond_min_multiple_of_fees};
pub const SEAT_SLASH_BPS: u64 = ${P.seat_slash_bps};
pub const SEAT_UNBONDING_SECONDS: u64 = ${P.seat_unbonding_seconds};
pub const VOTE_COMMIT_WINDOW_SECONDS: u64 = ${P.vote_commit_window_seconds};
pub const VOTE_REVEAL_WINDOW_SECONDS: u64 = ${P.vote_reveal_window_seconds};
pub const MAX_ARGUS_ROUNDS: u8 = ${P.max_argus_rounds};
pub const CLAIM_TIMEOUT_FORFEIT_BPS: u64 = ${P.claim_timeout_forfeit_bps};
pub const YIELD_FORFEIT_BPS: u64 = ${P.yield_forfeit_bps};
pub const YIELD_COOLDOWN_SECONDS: u64 = ${P.yield_cooldown_seconds};
pub const STANDING_HALF_LIFE_DAYS: u64 = ${P.standing_half_life_days};
pub const SEASON_LENGTH_DAYS: u64 = ${P.season_length_days};

// v1 frozen records (ADR-0002 / RewardMath.sol): the legacy law, not v2 parameters.
pub const LEGACY_FEE_BPS_V1: u64 = ${P.legacy_fee_bps_v1_frozen};
pub const LEGACY_BREAK_SPLIT_BPS_V1: u64 = ${P.legacy_break_split_v1_frozen};
`;

const ts = `// GENERATED by scripts/params-codegen.mjs from params/crucible.params.json — gate 732.
// Do not edit: change the JSON, re-run the generator, commit the diff.
// v2 arena parameters (ADR-0011). The v1 constants at the bottom are frozen records.

// ARENA_FEE_BPS, not FEE_BPS — see the note in params.rs: the legacy escrow's live FEE_BPS is 500.
export const ARENA_FEE_BPS = ${P.fee_bps}n;
export const TRIAL_OPEN_MAX_SECONDS = ${P.trial_open_max_seconds}n;
export const AGENT_BOND_MIN_BPS = ${P.agent_bond_min_bps}n;
export const CLAIM_DEADLINE_MIN_SECONDS = ${P.claim_deadline_min_seconds}n;
export const CLAIM_DEADLINE_MAX_SECONDS = ${P.claim_deadline_max_seconds}n;
export const MAX_ACTIVE_CLAIMS = ${P.max_active_claims}n;
export const SKEPTIC_WINDOW_MIN_SECONDS = ${P.skeptic_window_min_seconds}n;
export const SKEPTIC_WINDOW_MAX_SECONDS = ${P.skeptic_window_max_seconds}n;
export const SKEPTIC_STAKE_MIN_BPS = ${P.skeptic_stake_min_bps}n;
export const BREAK_REVEAL_GRACE_SECONDS = ${P.break_reveal_grace_seconds}n;
export const MAX_DOCKET = ${P.max_docket}n;
export const BREAK_PRIZE_BPS = ${P.break_prize_bps}n;
export const ARGUS_SEATS = ${P.argus_seats}n;
export const ARGUS_QUORUM = ${P.argus_quorum}n;
export const SEAT_FEE_BPS = ${P.seat_fee_bps}n;
export const SEAT_BOND_MIN_MULTIPLE = ${P.seat_bond_min_multiple_of_fees}n;
export const SEAT_SLASH_BPS = ${P.seat_slash_bps}n;
export const SEAT_UNBONDING_SECONDS = ${P.seat_unbonding_seconds}n;
export const VOTE_COMMIT_WINDOW_SECONDS = ${P.vote_commit_window_seconds}n;
export const VOTE_REVEAL_WINDOW_SECONDS = ${P.vote_reveal_window_seconds}n;
export const MAX_ARGUS_ROUNDS = ${P.max_argus_rounds}n;
export const CLAIM_TIMEOUT_FORFEIT_BPS = ${P.claim_timeout_forfeit_bps}n;
export const YIELD_FORFEIT_BPS = ${P.yield_forfeit_bps}n;
export const YIELD_COOLDOWN_SECONDS = ${P.yield_cooldown_seconds}n;
export const STANDING_HALF_LIFE_DAYS = ${P.standing_half_life_days}n;
export const SEASON_LENGTH_DAYS = ${P.season_length_days}n;

// v1 frozen records (ADR-0002 / RewardMath.sol): the legacy law, not v2 parameters.
export const LEGACY_FEE_BPS_V1 = ${P.legacy_fee_bps_v1_frozen}n;
export const LEGACY_BREAK_SPLIT_BPS_V1 = ${P.legacy_break_split_v1_frozen}n;
`;

if (check) {
  const drift = [];
  for (const [file, body] of [
    ["params.rs", rust],
    ["params.ts", ts],
  ]) {
    const onDisk = readFileSync(join(outDir, file), "utf8");
    if (onDisk !== body) drift.push(`params/generated/${file} differs from params/crucible.params.json — regenerate with: node scripts/params-codegen.mjs`);
  }
  if (drift.length > 0) {
    console.error(`params drift FAILED:\n  ${drift.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`params:check green — invariants hold, generated files match the JSON (gate 732)`);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "params.rs"), rust);
  writeFileSync(join(outDir, "params.ts"), ts);
  console.log(
    `params:codegen — invariants proven (5/5), wrote params/generated/{params.rs,params.ts} (gate 732)`,
  );
}
