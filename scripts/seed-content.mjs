#!/usr/bin/env node
/**
 * Pin the demo trial's content, and keep the on-chain commitment honest about it.
 *
 * A trial stores two `bytes32`s. Until now the seeds built them from strings that name nothing
 * — `keccak256(abi.encodePacked("spec-open", i, block.timestamp))` — so a skeptic who accepted
 * the invitation to break a demo trial could not fetch a spec, could not re-run a suite, and had
 * to be told the content does not exist. That is what the docs had to apologize for.
 *
 * Pin-then-post fixes it by reversing the order: the bytes go in the store first, the digest the
 * store reports is the one that goes on-chain. Two commands, because the Solidity scripts run in
 * a container that has no node in it:
 *
 *   node scripts/seed-content.mjs --write   # pin, and generate the constants the scripts use
 *   node scripts/seed-content.mjs --check   # pin again, and fail if the committed constants lie
 *
 * `--check` is the gate. The constants are generated, so they are not a second source of truth;
 * they are a *cached* one, and CI recomputes them from the bytes every run. A fixture edited
 * without regenerating, or a checkout that turned LF into CRLF, fails there rather than putting
 * a digest on a chain that resolves to nothing.
 */

import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CidStore, ContentBridge, DisclosureLog } from "@crucible/cidstore";
import { ContentService } from "@crucible/forge-runner";
import { digestOfContent } from "@crucible/smith";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES = path.join(ROOT, "fixtures", "trials", "counter");
const SOLIDITY_OUT = path.join(ROOT, "crucible-contracts", "script", "SeedContent.sol");

/** The suite's files, in a fixed order: the pinned bytes are the digest, so order is meaning. */
const SUITE_FILES = ["foundry.toml", "src/Counter.sol", "test/Counter.t.sol"];

const argv = process.argv.slice(2);
const mode = argv.includes("--write") ? "write" : argv.includes("--check") ? "check" : "pin";
const dirFlag = argv.indexOf("--dir");
const CONTENT_DIR =
  dirFlag >= 0 ? path.resolve(argv[dirFlag + 1]) : process.env.CRUCIBLE_CONTENT_DIR || path.join(ROOT, ".crucible-content");

async function readText(rel) {
  const text = await readFile(path.join(FIXTURES, rel), "utf8");
  // The other half of `.gitattributes`. A CR here is a checkout that rewrote the bytes, and a
  // rewrite is a different digest — on one machine only. Refusing is better than posting it.
  if (text.includes("\r")) {
    throw new Error(
      `${rel} contains CR bytes, so its digest would depend on this machine's checkout. ` +
        "The file must be LF (see .gitattributes); re-materialize it from the committed blob.",
    );
  }
  return text;
}

/**
 * The suite as a pinned tree.
 *
 * Keys sorted on the way in: `pinSuite` hashes `JSON.stringify` of this object, and an object
 * built in a different order is a different string, a different cid, and a different digest.
 */
async function suiteTree() {
  const files = {};
  for (const rel of [...SUITE_FILES].sort()) files[rel] = await readText(rel);
  return { files };
}

async function service() {
  return new ContentService({
    bridge: new ContentBridge({
      store: new CidStore({ dir: path.join(CONTENT_DIR, "store") }),
      disclosure: await DisclosureLog.open(path.join(CONTENT_DIR, "disclosure")),
      digestOf: digestOfContent,
    }),
  });
}

/**
 * Pin both halves and prove each digest resolves back to the bytes it was made from.
 *
 * That last step is not decoration. `--check` proves the committed constant matches a fresh
 * digest; it does not prove the store can answer for it. A pin that wrote nothing readable would
 * be caught here, by the same process that is supposed to be the only writer.
 */
async function pin(content) {
  const spec = await readText("SPEC.md");
  const tree = await suiteTree();
  const pinnedSpec = await content.pinText(spec);
  const pinnedSuite = await content.pinSuite(tree);

  const backSpec = await content.fetchTextByDigest(pinnedSpec.digest);
  if (backSpec !== spec) throw new Error(`the spec digest ${pinnedSpec.digest} did not resolve to the spec`);
  const backSuite = await content.fetchTextByDigest(pinnedSuite.digest);
  if (backSuite !== JSON.stringify(tree)) {
    throw new Error(`the suite digest ${pinnedSuite.digest} did not resolve to the pinned tree`);
  }

  return {
    spec: { ...pinnedSpec, bytes: spec.length },
    suite: { ...pinnedSuite, bytes: backSuite.length, files: Object.keys(tree.files).length },
  };
}

function generated(pinned) {
  return `// SPDX-License-Identifier: MIT
pragma solidity 0.8.26;

/**
 * GENERATED by scripts/seed-content.mjs --write. Do not edit by hand.
 *
 * The two digests a demo trial commits to, for content that is actually in the store. The seeds
 * used to invent these with keccak256(abi.encodePacked("spec-open", i, block.timestamp)), which
 * names a string no pinning process ever wrote: a skeptic who claimed such a trial had nothing
 * to fetch, so the deterministic phase could not run and the challenge went to the committee by
 * default — the guarantee the product is built on, silently unavailable on every demo trial.
 *
 * These constants are the digests of fixtures/trials/counter, pinned by the same ContentService
 * a verifier uses. CI runs \`node scripts/seed-content.mjs --check\`, which re-pins those files
 * and fails if anything here no longer answers to them. So the values are cached, not trusted.
 */
library SeedContent {
    /// fixtures/trials/counter/SPEC.md — pinned as ${pinned.spec.cid}
    bytes32 constant SPEC_HASH = ${hex(pinned.spec.digest)};

    /// fixtures/trials/counter (foundry.toml, src/Counter.sol, test/Counter.t.sol) — pinned as ${pinned.suite.cid}
    bytes32 constant TESTS_HASH = ${hex(pinned.suite.digest)};
}
`;
}

/** Solidity wants 0x + 64 lowercase hex; a cid or an odd-length digest must not slip through. */
function hex(digest) {
  if (!/^0x[0-9a-fA-F]{64}$/.test(digest)) {
    throw new Error(`${digest} is not a 32-byte hex digest — the pinning rule has changed`);
  }
  return digest.toLowerCase();
}

/** The two constants as committed, or null when the file is missing or unreadably hand-edited. */
async function committed() {
  if (!existsSync(SOLIDITY_OUT)) return null;
  const src = await readFile(SOLIDITY_OUT, "utf8");
  const spec = src.match(/bytes32 constant SPEC_HASH = (0x[0-9a-f]{64});/)?.[1];
  const tests = src.match(/bytes32 constant TESTS_HASH = (0x[0-9a-f]{64});/)?.[1];
  if (!spec || !tests) return null;
  return { spec, tests };
}

async function main() {
  if (!existsSync(CONTENT_DIR)) await (await import("node:fs/promises")).mkdir(CONTENT_DIR, { recursive: true });
  const content = await service();
  const pinned = await pin(content);

  console.log(`content store  ${CONTENT_DIR}`);
  console.log(`  spec   ${pinned.spec.digest}  ${pinned.spec.cid}  ${pinned.spec.bytes} bytes`);
  console.log(`  suite  ${pinned.suite.digest}  ${pinned.suite.cid}  ${pinned.suite.files} files`);

  if (mode === "write") {
    await writeFile(SOLIDITY_OUT, generated(pinned), "utf8");
    console.log(`  wrote ${path.relative(ROOT, SOLIDITY_OUT)}`);
    return;
  }

  if (mode === "check") {
    const committedDigests = await committed();
    if (!committedDigests) {
      throw new Error(
        `${path.relative(ROOT, SOLIDITY_OUT)} is missing or does not carry both constants — ` +
          "run `node scripts/seed-content.mjs --write`",
      );
    }
    if (
      committedDigests.spec !== pinned.spec.digest.toLowerCase() ||
      committedDigests.tests !== pinned.suite.digest.toLowerCase()
    ) {
      throw new Error(
        "the constants the seeds post do not match the content they name:\n" +
          `  SPEC_HASH  committed ${committedDigests.spec}  actual ${pinned.spec.digest}\n` +
          `  TESTS_HASH committed ${committedDigests.tests}  actual ${pinned.suite.digest}\n` +
          "The fixture bytes changed (or this checkout changed their line endings). Regenerate with --write.",
      );
    }
    console.log("  the committed constants answer to the bytes they name.");
  }
}

main().catch((err) => {
  console.error(`seed-content: ${err.message}`);
  process.exit(1);
});
