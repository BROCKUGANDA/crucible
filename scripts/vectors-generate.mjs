#!/usr/bin/env node
/**
 * Gate 752 — golden vectors for verdict.v2 parity (TS reference side).
 *
 * The vectors are GENERATED from this repo's live JCS implementation
 * (packages/crypto — the one door), never hand-written: what is committed is
 * exactly what the shipped code produces. Every other language answers the
 * same question against this file: sha256(JCS(body)) byte-for-byte.
 *
 *   TS    : node scripts/vectors-check.mjs                 (this side, green now)
 *   Rust  : canonicalize the same bodies, sha256, compare to vectors.json
 *   Solidity: sha256 over the COMMITTED jcs_hex bytes (contracts never
 *             canonicalize — they verify pre-canonicalized bytes)
 *
 * Verdict bodies are PURE by constitution §2.7: no floats, no timestamps, no
 * model/provider metadata — fixed-point integers and strings only. The cases
 * below pin the JCS traps that actually diverge across implementations: key
 * order, integer serialization, nested objects, and empty structures.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { jcsCanonicalize } = require(join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "packages",
  "crypto",
  "dist",
  "jcs.js",
));
import { createHash } from "node:crypto";

const cases = [
  { name: "pass-minimal", body: { verdict: "pass", trial: 1, suite: "code" } },
  {
    name: "fail-with-codes",
    body: { verdict: "fail", trial: 42, codes: ["holdout-fail", "replay-mismatch"], weight: 1200 },
  },
  {
    name: "key-order-independence",
    body: { suite: "code", trial: 1, verdict: "pass" }, // different insertion order, same JCS
  },
  { name: "empty-structures", body: { verdict: "void", codes: [], detail: {} } },
  {
    name: "nested-fixed-point",
    body: { verdict: "pass", scores: { correctness: 9800, style: 7500 }, per_probe: [1, 0, 1] },
  },
  { name: "unicode-payload-id", body: { verdict: "pass", trial: 7, tag: "probe.safety" } },
];

const vectors = {
  $comment: [
    "GENERATED by scripts/vectors-generate.mjs — do not edit by hand (gate 752).",
    "jcs = the exact canonical bytes (UTF-8); sha256 = sha256(jcs) hex, no 0x prefix.",
    "Rust and Solidity implementations must reproduce sha256 from their own JCS",
    "(Rust) or verify sha256 over jcs (Solidity, which never canonicalizes).",
  ],
  vectors: cases.map(({ name, body }) => {
    const jcs = jcsCanonicalize(body);
    return { name, body, jcs, sha256: createHash("sha256").update(jcs, "utf8").digest("hex") };
  }),
};

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "vectors", "verdict");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "vectors.json"), JSON.stringify(vectors, null, 2) + "\n");
console.log(`vectors:generate — ${cases.length} vectors written to vectors/verdict/vectors.json (gate 752, TS side)`);
