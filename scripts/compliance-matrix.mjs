/**
 * Gate 572 — Compliance matrix generator.
 *
 * Reads docs/gates.yml (gate → framework mappings) and emits a crawlable
 * compliance matrix at /compliance (JSON). Gate IDs × frameworks auto-built
 * from gate front-matter; published at /compliance, crawlable (ties 459–464).
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(process.cwd(), "docs");
const GATES_FILE = join(ROOT, "gates.yml");
const OUT_DIR = join(process.cwd(), "apps/web/src/app/compliance");
const OUT_FILE = join(OUT_DIR, "route.ts");

/** Minimal YAML parse for our simple list-of-maps format. */
function parseGatesYaml(text) {
  const gates = [];
  const frameworks = {};
  let current = null;
  let inFrameworks = false;

  for (const rawLine of text.split("\n")) {
    const line = rawLine.replace(/\r$/, "");
    if (!line.trim()) continue;

    if (line === "frameworks:") {
      inFrameworks = true;
      continue;
    }
    if (inFrameworks && line.startsWith("  ")) {
      const m = line.match(/^  ([a-z0-9-]+):\s*"(.*)"/);
      if (m) frameworks[m[1]] = m[2];
      continue;
    }
    inFrameworks = false;

    if (line.startsWith("- id:")) {
      if (current) gates.push(current);
      const m = line.match(/- id:\s*(\d+)/);
      current = { id: parseInt(m[1], 10), frameworks: [] };
    } else if (current && line.startsWith("  title:")) {
      current.title = line.replace(/^  title:\s*/, "");
    } else if (current && line.startsWith("  frameworks:")) {
      const list = line.replace(/^  frameworks:\s*\[/, "").replace(/\]$/, "");
      current.frameworks = list.split(",").map((s) => s.trim()).filter(Boolean);
    }
  }
  if (current) gates.push(current);

  return { gates, frameworks };
}

function buildMatrix(gates, frameworks) {
  const matrix = {};
  for (const g of gates) {
    matrix[String(g.id)] = {
      id: g.id,
      title: g.title,
      frameworks: g.frameworks,
    };
  }

  const byFramework = {};
  for (const [fw, name] of Object.entries(frameworks)) {
    byFramework[fw] = gates
      .filter((g) => g.frameworks.includes(fw))
      .map((g) => g.id)
      .sort((a, b) => a - b);
  }

  return { gates: matrix, byFramework, frameworks };
}

function emitRouteFile(matrix, byFramework, frameworks) {
  const gateEntries = Object.entries(matrix)
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(
      ([id, g]) =>
        `    { id: ${g.id}, title: ${JSON.stringify(g.title)}, frameworks: ${JSON.stringify(g.frameworks)} },`
    )
    .join("\n");

  const fwEntries = Object.entries(byFramework)
    .map(
      ([fw, ids]) =>
        `    ${JSON.stringify(fw)}: { name: ${JSON.stringify(frameworks[fw])}, gateIds: [${ids.join(", ")}] },`
    )
    .join("\n");

  return `// Auto-generated by scripts/compliance-matrix.mjs. Do not edit by hand.
// Gate 572 — compliance matrix auto-built from docs/gates.yml front-matter.
// Published at /compliance, crawlable (ties 459–464).

import type { Metadata } from "next";

export const metadata: Metadata = {
  title: "Compliance Matrix — CRUCIBLE",
  description: "Gate IDs × frameworks: OWASP Top 10, LLM Top 10, SCSVS, ISO 27001, NIST AI RMF, EU AI Act, SOC2-lite, SLSA/SBOM, SEO/GEO/AEO.",
};

const GATES = [
${gateEntries}
];

const BY_FRAMEWORK = {
${fwEntries}
};

const FRAMEWORK_NAMES = ${JSON.stringify(frameworks, null, 2)};

export default function CompliancePage() {
  return null;
}

export async function GET(): Promise<Response> {
  return new Response(
    JSON.stringify(
      {
        gates: GATES,
        byFramework: BY_FRAMEWORK,
        frameworks: FRAMEWORK_NAMES,
        totalGates: GATES.length,
        generatedAt: new Date().toISOString(),
      },
      null,
      2
    ),
    { headers: { "content-type": "application/json; charset=utf-8" } }
  );
}
`;
}

function main() {
  const text = readFileSync(GATES_FILE, "utf8");
  const { gates, frameworks } = parseGatesYaml(text);
  const { gates: matrix, byFramework } = buildMatrix(gates, frameworks);

  mkdirSync(OUT_DIR, { recursive: true });
  const routeContent = emitRouteFile(matrix, byFramework, frameworks);
  writeFileSync(OUT_FILE, routeContent);

  console.log(
    `Compliance matrix generated: ${gates.length} gates, ${Object.keys(frameworks).length} frameworks`
  );
  console.log(`Output: ${OUT_FILE}`);
}

main();
