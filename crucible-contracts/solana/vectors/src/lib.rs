//! Gate 752, Rust side — canonical serialization for verdict.v2 bodies.
//!
//! This is a deliberately scoped JCS (RFC 8785) subset, and the scope is not a
//! shortcut: the constitution (§2.7) bans floats, timestamps and provider
//! metadata from verdict bodies, which removes exactly the parts of full JCS
//! that are hard to reproduce (ECMAScript number formatting, surrogate sorting
//! of arbitrary keys). What remains for a *pure* body is:
//!
//!   - objects: keys sorted by UTF-16 code units (byte order for the ASCII
//!     keys a verdict carries), no whitespace, `":"` and `","` separators;
//!   - strings: JSON escaping (verdict strings are ASCII-safe by schema);
//!   - integers: plain decimal;
//!   - arrays and nesting, recursively.
//!
//! Parity is proven against `vectors/verdict/vectors.json` — six vectors
//! generated from the TypeScript reference implementation, never hand-written.
//! If a verdict body ever needs a float, that is a §2.7 violation first and a
//! canonicalization gap second.

use serde_json::Value;
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::fmt::Write;

/// Canonical bytes for a pure verdict.v2 body. Panics on a float or a
/// non-finite number — both are §2.7 violations and must never reach hashing.
pub fn jcs_subset(value: &Value) -> String {
    let mut out = String::new();
    write_value(&mut out, value);
    out
}

fn write_value(out: &mut String, value: &Value) {
    match value {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => {
            if let Some(u) = n.as_u64() {
                let _ = write!(out, "{u}");
            } else if let Some(i) = n.as_i64() {
                let _ = write!(out, "{i}");
            } else {
                panic!("floats are banned from verdict bodies (§2.7): {n}");
            }
        }
        Value::String(s) => write_string(out, s),
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_value(out, item);
            }
            out.push(']');
        }
        Value::Object(map) => {
            // BTreeMap<&str, &Value> sorts by byte order, which equals UTF-16
            // code-unit order for the ASCII keys the verdict schema carries.
            let sorted: BTreeMap<&str, &Value> = map.iter().map(|(k, v)| (k.as_str(), v)).collect();
            out.push('{');
            for (i, (k, v)) in sorted.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_string(out, k);
                out.push(':');
                write_value(out, v);
            }
            out.push('}');
        }
    }
}

fn write_string(out: &mut String, s: &str) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

/// sha256 over the canonical bytes, lowercase hex — the verdict hash.
pub fn verdict_hash(value: &Value) -> String {
    let bytes = jcs_subset(value);
    let digest = Sha256::digest(bytes.as_bytes());
    let mut hex = String::with_capacity(64);
    for b in digest {
        let _ = write!(hex, "{b:02x}");
    }
    hex
}

/// The committed golden vectors, generated by `scripts/vectors-generate.mjs`
/// from the TypeScript reference. The relative path escapes the workspace —
/// intentional: one source of truth at the repo root, no copies to drift.
pub const VECTORS_JSON: &str = include_str!("../../../../vectors/verdict/vectors.json");

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;

    #[test]
    fn rust_reproduces_every_ts_vector_byte_for_byte() {
        let file = serde_json::from_str::<Value>(VECTORS_JSON).expect("vectors.json parses");
        let vectors = file["vectors"].as_array().expect("vectors array");
        assert!(vectors.len() >= 6, "expected the six committed vectors");
        for v in vectors {
            let name = v["name"].as_str().unwrap();
            let body = &v["body"];
            let expected_jcs = v["jcs"].as_str().unwrap();
            let expected_sha = v["sha256"].as_str().unwrap();
            assert_eq!(jcs_subset(body), expected_jcs, "{name}: canonical bytes");
            assert_eq!(verdict_hash(body), expected_sha, "{name}: sha256");
        }
    }

    #[test]
    fn a_float_is_refused_rather_than_canonicalized() {
        let bad = serde_json::from_str::<Value>(r#"{"score": 0.5}"#).unwrap();
        let result = std::panic::catch_unwind(|| jcs_subset(&bad));
        assert!(result.is_err(), "§2.7: floats must never reach hashing");
    }

    #[test]
    fn key_order_independence_holds() {
        let a = serde_json::from_str::<Value>(r#"{"suite":"code","trial":1,"verdict":"pass"}"#).unwrap();
        let b = serde_json::from_str::<Value>(r#"{"verdict":"pass","trial":1,"suite":"code"}"#).unwrap();
        assert_eq!(jcs_subset(&a), jcs_subset(&b));
    }
}
